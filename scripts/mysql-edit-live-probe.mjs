import assert from 'node:assert/strict';
import { createMysqlEditLiveFixture } from './mysql-edit-live-fixture.mjs';
import { DesktopMysqlEditor } from '../src/desktop-mysql-editor.mjs';
import { MysqlPluginRuntime } from '../src/mysql-plugin-runtime.mjs';

let fixture;
try {
  fixture=await createMysqlEditLiveFixture();
  const admin=fixture.admin;
  await admin.query("CREATE TABLE items (id BIGINT UNSIGNED NOT NULL, tenant INT NOT NULL, label VARCHAR(100) NOT NULL UNIQUE, amount DECIMAL(30,8), stamp DATETIME(6), state ENUM('open','closed') NOT NULL DEFAULT 'open', document JSON, payload VARBINARY(32), quantity INT NOT NULL DEFAULT 1, doubled INT GENERATED ALWAYS AS (quantity * 2) STORED, PRIMARY KEY (tenant,id)) ENGINE=InnoDB");
  await admin.query("INSERT INTO items(id,tenant,label,amount,stamp,document,payload) VALUES (9007199254740993,1,'first',12345678901234567890.12345678,'2024-02-29 12:34:56.123456',?,?), (9007199254740994,1,'second',2.0,'2024-02-29 00:00:00',?,?), (9007199254740993,2,'other-tenant',3.0,NULL,?,?)",['{"large":9007199254740993,"label":"中文"}',Buffer.from([0,255,1]),'{"state":"fixture"}',Buffer.from([4,5]),'{}',Buffer.from([6])]);
  const plugin={projectId:'live-project',environmentId:'live-test',pluginInstanceId:'live-mysql',pluginType:'mysql',displayName:'隔离测试数据库',revision:1,target:{database:fixture.database},limits:{maxRows:100,maxBytes:1048576,timeoutMs:5000}};
  const runtime=new MysqlPluginRuntime({closeRelay:async()=>{}},{});
  const resource='live-project/live-test/live-mysql';
  const connect=async()=>{
    const session={connection:await fixture.connect()};
    runtime.sessions.set(resource,session);return session;
  };
  let session=await connect();
  const audits=[];
  const editor=new DesktopMysqlEditor(runtime,{appendAudit:async(_project,event)=>{audits.push(event);}});
  const open=sql=>editor.open('live-window',plugin,{sql:sql??'SELECT * FROM items ORDER BY tenant,id'});
  const prepare=(snapshot,changes)=>editor.prepare('live-window',plugin,{editId:snapshot.editId,changes});
  const commit=(snapshot,plan)=>editor.commit('live-window',plugin,{editId:snapshot.editId,planId:plan.planId});
  const read=async()=>{const [rows]=await admin.query({sql:'SELECT tenant,id,label,amount,quantity FROM items ORDER BY tenant,id',bigNumberStrings:true});return rows.map(row=>({...row}));};
  let checks=0;
  let snapshot=await open();
  assert.equal(snapshot.rows[0].values.id,'9007199254740993');
  assert.equal(snapshot.rows[0].values.amount,'12345678901234567890.12345678');
  assert.equal(snapshot.rows[0].values.stamp,'2024-02-29 12:34:56.123456');
  assert.match(snapshot.rows[0].values.document,/9007199254740993/u);
  assert.match(snapshot.rows[0].values.document,/中文/u);
  assert.equal(snapshot.columns.find(column=>column.name==='doubled').editable,false);
  assert.equal(snapshot.columns.find(column=>column.name==='payload').editable,false);
  checks++;
  let plan=prepare(snapshot,[{rowId:snapshot.rows[0].rowId,values:{label:"中文 ' 修改",amount:'12345678901234567891.87654321',stamp:'2025-01-02 03:04:05.654321',quantity:'3'}}]);
  let saved=await commit(snapshot,plan);
  assert.equal(saved.status,'success',JSON.stringify(saved.error));
  assert.equal(saved.result.rows[0].values.doubled,'6');
  const successful=await read();
  assert.equal(successful[0].label,"中文 ' 修改");
  assert.equal(successful[0].amount,'12345678901234567891.87654321');
  assert.equal(successful[2].label,'other-tenant');
  assert.equal((await commit(snapshot,plan)).status,'success');
  assert.deepEqual(await read(),successful);checks++;
  await session.connection.query("SET SESSION sql_mode = 'STRICT_TRANS_TABLES,NO_BACKSLASH_ESCAPES'");
  snapshot=await open();
  const quotedValue="literal \\ ' OR 1=1 --";
  plan=prepare(snapshot,[{rowId:snapshot.rows[0].rowId,values:{label:quotedValue}}]);
  assert.equal((await commit(snapshot,plan)).status,'success');
  assert.equal((await read())[0].label,quotedValue);
  assert.equal((await read())[1].label,'second');
  await session.connection.query("SET SESSION sql_mode = 'STRICT_TRANS_TABLES'");checks++;
  snapshot=await open('SELECT i.tenant AS tenant_key,i.id AS key_id,i.label AS display_label FROM items i WHERE tenant = 1 ORDER BY id LIMIT 2');
  plan=prepare(snapshot,snapshot.rows.map((row,index)=>({rowId:row.rowId,values:{display_label:'alias-'+index}})));
  assert.equal((await commit(snapshot,plan)).status,'success');
  assert.equal((await read())[2].label,'other-tenant');checks++;
  snapshot=await open();
  plan=prepare(snapshot,snapshot.rows.slice(0,2).map(row=>({rowId:row.rowId,values:{state:'closed'}})));
  assert.equal((await commit(snapshot,plan)).status,'success');
  const [states]=await admin.query('SELECT state FROM items ORDER BY tenant,id');
  assert.deepEqual(states.map(row=>row.state),['closed','closed','open']);checks++;
  snapshot=await open();const beforeRollback=await read();
  plan=prepare(snapshot,snapshot.rows.slice(0,2).map(row=>({rowId:row.rowId,values:{label:'same-unique-value'}})));
  assert.equal((await commit(snapshot,plan)).status,'failed');
  assert.deepEqual(await read(),beforeRollback);checks++;
  snapshot=await open();
  plan=prepare(snapshot,[{rowId:snapshot.rows[0].rowId,values:{label:'must-not-overwrite'}}]);
  await admin.query("UPDATE items SET label='external-change' WHERE tenant=1 AND id=9007199254740993");
  saved=await commit(snapshot,plan);
  assert.equal(saved.error.code,'MYSQL_EDIT_CONFLICT');
  assert.equal((await read())[0].label,'external-change');checks++;
  snapshot=await open();
  plan=prepare(snapshot,[{rowId:snapshot.rows[1].rowId,values:{label:'must-not-resurrect'}}]);
  await admin.query('DELETE FROM items WHERE tenant=1 AND id=9007199254740994');
  assert.equal((await commit(snapshot,plan)).error.code,'MYSQL_EDIT_CONFLICT');
  assert.equal((await read()).length,2);checks++;
  snapshot=await open();
  plan=prepare(snapshot,[{rowId:snapshot.rows[0].rowId,values:{label:'before-commit-disconnect'}}]);
  const [[connectionId]]=await session.connection.query('SELECT CONNECTION_ID() AS id');
  const original=session.connection.execute.bind(session.connection);
  session.connection.execute=async request=>{
    const result=await original(request);
    if(request.sql?.startsWith('UPDATE '))await admin.query('KILL CONNECTION '+Number(connectionId.id));
    return result;
  };
  assert.equal((await commit(snapshot,plan)).status,'failed');
  assert.equal((await read())[0].label,'external-change');checks++;
  session=await connect();
  snapshot=await open();
  plan=prepare(snapshot,[{rowId:snapshot.rows[0].rowId,values:{label:'commit-ack-lost'}}]);
  const originalCommit=session.connection.query.bind(session.connection);
  session.connection.query=async request=>{
    const result=await originalCommit(request);
    if(request.sql==='COMMIT')throw Object.assign(new Error('模拟提交响应丢失'),{code:'ECONNRESET'});
    return result;
  };
  assert.equal((await commit(snapshot,plan)).status,'unknown');
  assert.equal((await read())[0].label,'commit-ack-lost');
  assert.equal((await commit(snapshot,plan)).status,'unknown');checks++;
  assert.doesNotMatch(JSON.stringify(audits),/12345678901234567891|commit-ack-lost|中文 ' 修改|external-change|before-commit-disconnect/u);checks++;
  console.log(JSON.stringify({ok:true,checks,engine:'MySQL 8.4',coverage:['复合主键定位','精度与中文','字段别名','多行赋值','唯一约束回滚','并发修改','并发删除','提交前断线回滚','提交响应丢失不重试','审计不保存业务值','特殊 SQL 模式参数绑定']}));
} catch(error) {
  console.error(JSON.stringify({ok:false,code:error.code??error.name,message:error.name==='AssertionError'?error.message:'真实 MySQL 验证未通过，未输出原始连接错误。'}));
  process.exitCode=1;
} finally { if(fixture)await fixture.close(); }
