const assert = require('node:assert/strict');
module.exports = async ({win,waitFor,workspaceProjects,pluginsByEnvironment,readCalls,setPluginRead,setCodexGate}) => {
  const evaluate = code => win.webContents.executeJavaScript(code,true);
  const click = selector => evaluate('document.querySelector('+JSON.stringify(selector)+').click()');
  const until = (code,label) => waitFor(win,code,label);
  const scope={projectId:'project-data',environmentId:'env-complete-search'};
  const records=Array.from({length:8},(_,index)=>({...scope,pluginInstanceId:'search-plugin-'+index,pluginType:'server',displayName:'未展开搜索插件 '+(index+1),revision:1,configState:'ready',target:{host:'search.example.invalid',port:22},auth:{username:'operator',type:'agent'},uplink:{type:'direct'},sources:[],assessment:{phase:'disconnected'}}));
  const project=workspaceProjects.find(item=>item.projectId===scope.projectId);
  project.environments.push({...scope,name:'未展开搜索环境',revision:1,pluginCount:8,readyPluginCount:8,draftCount:0,resourcePreview:records.slice(0,6),resourcePreviewTruncated:true});
  project.environmentCount++; project.pluginCount+=8; project.revision++;
  pluginsByEnvironment[scope.environmentId]=records;
  let fail=true;
  setPluginRead(target=>{if(target.environmentId===scope.environmentId && fail) throw new Error('模拟插件列表暂时不可用');});
  win.webContents.send('v2:workspace-changed',{type:'environment-created',...scope});
  await new Promise(resolve=>setTimeout(resolve,200));
  assert.equal(readCalls.some(call=>call.channel==='v2:plugin-list' && call.args[0]?.environmentId===scope.environmentId),false,'新环境尚未展开或加载');
  await evaluate("document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'k',ctrlKey:true,bubbles:true,cancelable:true}))");
  await until("document.querySelector('[data-testid=global-command]')?.textContent.includes('部分插件未读取完整')",'搜索失败明确说明范围');
  fail=false;
  await evaluate("[...document.querySelectorAll('[data-testid=global-command] button')].find(button=>button.textContent==='重新读取全部插件').click()");
  await until("document.querySelector('[data-testid=global-command]')?.textContent.includes('未展开搜索插件 8')",'搜索包含预览之外的第八个插件');
  await evaluate("(() => {const input=document.querySelector('[cmdk-input]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'未展开搜索插件 8');input.dispatchEvent(new Event('input',{bubbles:true}));})()");
  await until("[...document.querySelectorAll('[cmdk-item]')].some(item=>item.getClientRects().length && item.textContent.includes('未展开搜索插件 8'))",'按第八个插件名称搜索');
  await evaluate("[...document.querySelectorAll('[cmdk-item]')].find(item=>item.getClientRects().length && item.textContent.includes('未展开搜索插件 8')).click()");
  await until("document.querySelector('[data-testid=detail-workspace]')?.textContent.includes('未展开搜索插件 8')",'搜索结果跳转正确插件');
  await until("document.querySelector('[data-testid=plugin-open-workspace]')?.disabled === true",'新离线工作区不可打开');
  await evaluate("document.querySelector('[data-testid=plugin-open-workspace]').parentElement.focus()");
  await until("[...document.querySelectorAll('[role=tooltip]')].some(item=>item.textContent.includes('请先连接服务器'))",'键盘聚焦可查看禁用原因');
  setPluginRead(null);
  await click('[data-testid=settings-open]'); await click('[data-testid=settings-agent]');
  await until("document.querySelector('[data-testid=codex-refresh]')?.disabled === false",'应用设置初次检测完成');
  let release;
  const held = new Promise(resolve=>{release=resolve;}); setCodexGate(()=>held);
  await click('[data-testid=codex-refresh]');
  await until("document.querySelector('[data-testid=codex-refresh]').disabled",'重新检测正在等待');
  assert.equal(await evaluate("document.querySelector('[data-testid=settings-back]').disabled"),false,'只读检测不锁定返回');
  await click('[data-testid=settings-back]'); setCodexGate(null); release();
  await until("!document.querySelector('[data-testid=settings-page]')",'检测期间允许返回');
  await click('[data-testid=workspace-switcher]');
  await until("document.querySelector('[data-testid=workspace-manager]')?.textContent.includes('尚未打开工作区')",'工作区管理空态');
  await click('[data-testid=workspace-manager] [data-slot=dialog-close]');
  process.stdout.write('交互优化通过：完整插件搜索、失败重试、禁用原因可聚焦、只读设置可离开、工作区管理入口。\n');
};
