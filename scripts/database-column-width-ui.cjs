const assert=require('node:assert/strict');
module.exports=async function({win,click,waitFor,testId,databaseCalls,screenshot}) {
  const evaluate=source=>win.webContents.executeJavaScript(source,true);
  const selector='[data-testid=mysql-preview-result] [data-testid=mysql-column-resizer]';
  const widths=()=>evaluate(`Array.from(document.querySelectorAll('${selector}')).map(e=>Number(e.getAttribute('aria-valuenow')))`);
  const key=async keyCode=>{win.webContents.sendInputEvent({type:'keyDown',keyCode});win.webContents.sendInputEvent({type:'keyUp',keyCode});await new Promise(resolve=>setTimeout(resolve,80));};
  const handlePoint=()=>evaluate(`(()=>{const e=document.querySelector('${selector}');e.scrollIntoView({block:'nearest',inline:'nearest'});const r=e.getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
  const drag=async(delta,cancel=false)=>{
    win.webContents.focus();
    const point=await handlePoint();
    const hit=await evaluate(`document.elementFromPoint(${point.x},${point.y})?.outerHTML`);
    assert.match(hit,/mysql-column-resizer/,'列宽手柄必须可命中');
    win.webContents.sendInputEvent({type:'mouseMove',...point});
    win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});
    await new Promise(resolve=>setTimeout(resolve,50));
    win.webContents.sendInputEvent({type:'mouseMove',x:point.x+delta,y:point.y});
    await new Promise(resolve=>setTimeout(resolve,100));
    if(cancel)await key('ESCAPE');
    win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,x:point.x+delta,y:point.y});
    await new Promise(resolve=>setTimeout(resolve,100));
  };
  const initial=await widths(),calls=databaseCalls.length;
  assert.ok(initial[0]<168,'短主键不再占用统一大列宽');
  const size=await evaluate(`(()=>{const table=document.querySelector('[data-testid=mysql-preview-result] table');return {width:table.getBoundingClientRect().width,columns:[...table.querySelectorAll('col')].reduce((sum,col)=>sum+parseFloat(col.style.width),0)}})()`);
  assert.ok(Math.abs(size.width-size.columns)<=1,'表格不拉伸列来填满视口');
  await drag(57);
  const dragged=await widths();assert.equal(dragged[0],initial[0]+57);assert.deepEqual(dragged.slice(1),initial.slice(1),'只改变当前列宽');
  assert.equal(databaseCalls.length,calls,'拖动不能触发排序或查询');
  await drag(-30,true);assert.deepEqual(await widths(),dragged,'Esc 撤销本次拖动');
  await evaluate(`document.querySelector('${selector}').focus()`);await key('RIGHT');
  assert.equal((await widths())[0],dragged[0]+8,'键盘微调列宽');
  const saved=await widths();
  await click(win,testId('mysql-preview-run'));
  await waitFor(win,`document.querySelector('${selector}')?.getAttribute('aria-valuenow')==='${saved[0]}'`,'重新查询保留列宽');
  assert.deepEqual(await widths(),saved);
  const stored=await evaluate("Object.keys(localStorage).filter(key=>key.startsWith('mysql-column-widths:v1:')).map(key=>JSON.parse(localStorage.getItem(key)))");
  assert.ok(stored.length>0);assert.ok(stored.every(values=>Array.isArray(values)&&values.every(value=>typeof value==='number')),'本地仅保存列宽，不保存数据内容');
  await click(win,'[data-testid=mysql-table-close][data-table-name=orders]');
  await click(win,'[data-testid=mysql-table-item][data-table-name=orders]');
  await waitFor(win,`document.querySelector('${selector}')?.getAttribute('aria-valuenow')==='${saved[0]}'`,'关闭后重开同一表恢复列宽');
  assert.deepEqual(await widths(),saved);

  const beforeFit=databaseCalls.length,point=await handlePoint();
  win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:2,...point});
  await new Promise(resolve=>setTimeout(resolve,50));
  win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:2,...point});
  await waitFor(win,`Number(document.querySelector('${selector}')?.getAttribute('aria-valuenow'))<${saved[0]}`,'双击边界适应内容');
  assert.equal(databaseCalls.length,beforeFit,'双击适应不能触发排序');
  const header="[data-testid=mysql-preview-result] th[data-column-index='0']";
  await evaluate(`document.querySelector(${JSON.stringify(header)}).dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:500,clientY:300}))`);
  await waitFor(win,"[...document.querySelectorAll('[role=menuitem]')].some(e=>e.textContent==='适应全部列宽')",'表头列宽菜单');
  await evaluate("[...document.querySelectorAll('[role=menuitem]')].find(e=>e.textContent==='重置列宽').click()");
  await waitFor(win,`document.querySelector('${selector}')?.getAttribute('aria-valuenow')==='${initial[0]}'`,'重置默认宽度');
  await screenshot(win,'content-column-widths');
};
