const assert = require('node:assert/strict');

module.exports = async function ({win,click,fill,waitFor,testId,active,openKey,menuAction,state,calls,writeValues,value,stamp,publish}) {
  const evaluate = source => win.webContents.executeJavaScript(source,true);
  const pause = ms => new Promise(resolve=>setTimeout(resolve,ms));
  const until = async (predicate,label) => { const end=Date.now()+5000;while(!predicate()&&Date.now()<end)await pause(20);assert.ok(predicate(),label); };
  const offline = async () => { publish('disconnected');await waitFor(win,"document.querySelector('[data-testid=redis-workspace-disconnected]')",'断线保留工作区'); };
  const online = async () => { publish('connected');await waitFor(win,"!document.querySelector('[data-testid=redis-workspace-disconnected]')",'重连同步保留工作区'); };
  const refresh = async () => { await click(win,active('redis-refresh-key'));await waitFor(win,"!document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-key-stale]')",'重新读取当前 Key'); };
  const button = async label => { await evaluate(`[...document.querySelectorAll('button')].find(e=>e.getClientRects().length&&e.textContent===${JSON.stringify(label)}).click()`);await pause(70); };
  const tabKeys = () => evaluate("[...document.querySelectorAll('[data-testid=redis-key-tab]')].map(e=>e.title)");
  await click(win,testId('redis-workspace-reconnect'));
  await waitFor(win,"!document.querySelector('[data-testid=redis-workspace-disconnected]')",'原地重连');
  await click(win,testId('redis-refresh-keys'));
  await menuAction(win,'redis-browser-menu','redis-tree-expand-all');
  await openKey(win,'cache:text',true);
  await openKey(win,'cache:list',true);
  await fill(win,testId('redis-search-input'),'cache:');
  await click(win,testId('redis-search-submit'));
  const tabs = await tabKeys();
  const activeBefore = await evaluate("document.querySelector('[data-testid=redis-key-tab][aria-selected=true]').title");
  const beforeDisconnect = calls.length;
  await offline();
  assert.deepEqual(await tabKeys(),tabs);
  assert.equal(await evaluate("document.querySelector('[data-testid=redis-key-tab][aria-selected=true]').title"),activeBefore);
  assert.equal(await evaluate("document.querySelector('[data-testid=redis-search-input]').value"),'cache:');
  assert.equal(await evaluate("document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-refresh-key]').disabled"),true);
  assert.equal(await evaluate("document.querySelector('[data-testid=redis-search-submit]').disabled"),true);
  await pause(100);
  assert.equal(calls.length,beforeDisconnect,'离线不继续扫描或读取');
  state.failReconnect = true;
  await click(win,testId('redis-workspace-reconnect'));
  await waitFor(win,"document.querySelector('[data-testid=redis-workspace-reconnect]')?.disabled===false",'重连失败允许重试');
  assert.deepEqual(await tabKeys(),tabs,'重连失败保留标签');
  state.failReconnect = false;
  await click(win,testId('redis-workspace-reconnect'));
  await waitFor(win,"!document.querySelector('[data-testid=redis-workspace-disconnected]')",'重试成功');
  assert.equal(calls.length,beforeDisconnect,'重连不自动重新读取');
  assert.deepEqual(await tabKeys(),tabs);
  assert.equal(await evaluate("document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-delete-key]').disabled"),true,'旧结果不能直接删除');
  await refresh();

  // 连接失效后集合分页和搜索游标不可继续使用。
  const contentHold = {operation:'read',data:{key:'cache:list',type:'list',exists:true,rows:[{id:'old-row',index:0,value:value('旧分页内容')}],nextCursor:'old-content-cursor',complete:false,truncated:false,readAt:stamp()}};
  state.hold = contentHold;
  await click(win,active('redis-refresh-key'));
  await until(()=>contentHold.release,'集合读取已挂起');contentHold.release();
  await waitFor(win,"document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-content-more]')",'旧集合游标已建立');
  state.scanPages=[{keys:Array.from({length:500},(_,i)=>'cache:page:'+i),nextCursor:'old-search-cursor',complete:false}];
  await click(win,testId('redis-refresh-keys'));
  await waitFor(win,"document.querySelector('[data-testid=redis-scan-more]')",'旧扫描游标已建立');
  const oldCursorEnd=calls.length;
  publish('disconnected');publish('connected');
  await waitFor(win,"!document.querySelector('[data-testid=redis-scan-more]')&&!document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-content-more]')",'快速断重连清除两类游标');
  await refresh();
  await click(win,testId('redis-refresh-keys'));
  await waitFor(win,"document.querySelector('[data-redis-key=\"cache:text\"]')",'从头重新搜索');
  assert.ok(calls.slice(oldCursorEnd).every(call=>!['old-content-cursor','old-search-cursor'].includes(call.payload.cursor)));

  // 新连接读取不等待旧连接，迟到内容不能覆盖新快照。
  await menuAction(win,'redis-browser-menu','redis-tree-expand-all');
  await openKey(win,'cache:text',true);
  const oldRead={operation:'read',data:{key:'cache:text',type:'string',exists:true,rows:[],nextCursor:null,complete:true,truncated:false,readAt:stamp(),value:value('迟到旧连接内容')}};
  state.hold=oldRead;
  await click(win,active('redis-refresh-key'));
  await until(()=>oldRead.release,'旧内容读取已挂起');
  await offline();await online();
  await refresh();
  oldRead.release();await pause(100);
  assert.equal(await evaluate("document.body.textContent.includes('迟到旧连接内容')"),false,'旧内容不回填');
  state.scanPages=[{keys:['cache:late-old-scan'],nextCursor:'late-scan-cursor',complete:false,hold:true}];
  await click(win,testId('redis-refresh-keys'));
  await until(()=>state.releaseScan,'旧扫描已挂起');
  const releaseScan=state.releaseScan;state.releaseScan=null;
  await offline();await online();
  await click(win,testId('redis-refresh-keys'));
  await waitFor(win,"document.querySelector('[data-redis-key=\"cache:text\"]')",'新扫描不等待旧请求');
  releaseScan();await pause(100);
  assert.equal(await evaluate("document.body.textContent.includes('late-old-scan')"),false);

  // 手动断开保留草稿，离线修改只留在内存；新连接仍须重新核对。
  await click(win,testId('redis-create-key'));
  await fill(win,'[aria-label="新增 Key 名称"]','cache:retained-draft');
  await fill(win,'[aria-label="Redis Value"]','{"draft":1}');
  await click(win,testId('redis-workspace-disconnect'));
  await waitFor(win,"document.querySelector('[data-testid=redis-workspace-disconnected]')",'手动断开保留编辑器');
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Redis Value\"]').value"),'{"draft":1}');
  await fill(win,'[aria-label="Redis Value"]','{"draft":2}');
  await online();
  assert.equal(await evaluate("document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-save-value]').disabled"),true);
  assert.equal(writeValues.has('cache:retained-draft'),false);
  await button('重新核对');
  const prepareHold={operation:'prepare'};state.writeHold=prepareHold;
  const beforePrepare=state.writeCommits;
  await click(win,active('redis-save-value'));
  await until(()=>prepareHold.release,'写入准备已挂起');
  await offline();await online();prepareHold.release();
  await waitFor(win,"document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-save-value]')?.getAttribute('aria-busy')==='false'",'迟到准备响应结束');
  assert.equal(state.writeCommits,beforePrepare,'断线前准备响应不能提交');
  assert.equal(await evaluate("document.querySelector('[aria-label=\"Redis Value\"]').value"),'{"draft":2}');
  await button('重新核对');
  await click(win,active('redis-save-value'));
  await waitFor(win,"!document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-value-editor]')",'明确保存成功');
  await waitFor(win,"document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-delete-key]')?.disabled===false",'保存后读取新内容');
  assert.equal(writeValues.get('cache:retained-draft').value,'{"draft":2}');

  // 删除确认在断线时作废，重连不能消费旧授权。
  await click(win,active('redis-delete-key'));
  await waitFor(win,"document.querySelector('[data-testid=redis-confirm-delete]')",'删除确认已打开');
  const beforeDelete=state.writeCommits;
  await offline();
  await waitFor(win,"!document.querySelector('[data-testid=redis-confirm-delete]')",'断线关闭旧删除确认');
  await online();
  assert.equal(state.writeCommits,beforeDelete);
  assert.equal(writeValues.has('cache:retained-draft'),true);
  await refresh();
  await click(win,active('redis-delete-key'));
  await waitFor(win,"document.querySelector('[data-testid=redis-confirm-delete]')",'重新打开删除确认');
  const deletePrepareHold={operation:'prepare'};state.writeHold=deletePrepareHold;
  await click(win,testId('redis-confirm-delete'));
  await until(()=>deletePrepareHold.release,'删除准备已挂起');
  await offline();await online();deletePrepareHold.release();
  await waitFor(win,"!document.querySelector('[data-testid=redis-confirm-delete]')",'迟到删除准备不恢复旧确认');
  await pause(100);
  assert.equal(state.writeCommits,beforeDelete,'断线前的删除准备不能继续提交');
  assert.equal(writeValues.has('cache:retained-draft'),true);
  await refresh();
  await click(win,active('redis-edit-value'));
  await fill(win,'[aria-label="Redis Value"]','{"draft":3}');
  const commitHold={operation:'commit'};state.writeHold=commitHold;state.loseWriteReply=true;
  await click(win,active('redis-save-value'));
  await until(()=>commitHold.release,'写入提交已挂起');
  await offline();await online();commitHold.release();
  await waitFor(win,"document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-check-save]')",'提交应答丢失仍保留核实入口');
  assert.equal(state.writeCommits,beforeDelete+1,'重连不重复写入');
  await click(win,active('redis-check-save'));
  await waitFor(win,"!document.querySelector('.redis-tab-panel:not([hidden]) [data-testid=redis-value-editor]')",'核实结果后恢复浏览');
  assert.equal(state.writeCommits,beforeDelete+1);
  await click(win,testId('redis-workspace-close'));
  await click(win,testId('redis-workspace-confirm-close'));
  await waitFor(win,"!document.querySelector('[data-testid=redis-workspace]')",'明确关闭才清除工作区');
  process.stdout.write('Redis 断重连通过：标签、搜索、草稿保留，游标和迟到读取失效，旧确认取消，未知写入不重试。\n');
};
