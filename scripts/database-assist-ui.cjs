const assert = require('node:assert/strict');
function browseFixture({ where = '', orderBy = [], offset = 0, limit = 20 }) {
  let rows = Array.from({ length:65 }, (_,index) => ({ id:index+1,label:'浏览记录 '+(index+1),optional:null }));
  const minimum = /id\s*>=\s*(\d+)/u.exec(where);
  if (minimum) rows = rows.filter(row => row.id >= Number(minimum[1]));
  if (orderBy[0]?.direction === 'desc') rows.reverse();
  rows = rows.slice(offset,offset+limit);
  return {rows,rowCount:rows.length,bytes:Buffer.byteLength(JSON.stringify(rows)),truncated:false,columns:[{name:'id',table:'orders',type:3},{name:'label',table:'orders',type:253},{name:'optional',table:'orders',type:253}],durationMs:12,fingerprint:'fixture-browse',limitsApplied:{maxRows:100,maxBytes:262144,timeoutMs:10000}};
}
async function assertSqlAssistanceAndBrowse({win,fill,click,waitFor,textContains,testId,screenshot,state,databaseCalls,PRIMARY_ID}) {
  const evaluate = source => win.webContents.executeJavaScript(source,true);
  await fill(win,testId('mysql-sql-editor'),'SELECT\nFROM');
  const beforeLint = databaseCalls.length;
  await textContains(win,'mysql-sql-diagnostic','语法不完整或有误');
  assert.equal(databaseCalls.length,beforeLint,'基础语法诊断不得执行查询');
  await fill(win,testId('mysql-sql-editor'),'SELECT o. FROM orders o');
  await evaluate("(() => { const editor=document.querySelector('[data-testid=mysql-sql-editor]'); editor.focus(); editor.setSelectionRange(9,9); editor.dispatchEvent(new KeyboardEvent('keyup',{key:'.',bubbles:true})); })()");
  await textContains(win,'mysql-sql-completions','bigint');
  await screenshot(win,'sql-completion');
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'TAB'});
  win.webContents.sendInputEvent({type:'keyUp',keyCode:'TAB'});
  await waitFor(win,"document.querySelector('[data-testid=mysql-sql-editor]').value === 'SELECT o.`id` FROM orders o'",'别名字段补全插入');
  await textContains(win,'mysql-sql-diagnostic','基础语法通过');
  const original = await evaluate("document.querySelector('[data-testid=mysql-sql-editor]').value");
  await evaluate("(() => { const transfer=new DataTransfer(); document.querySelector('[data-table-name=orders]').dispatchEvent(new DragEvent('dragstart',{dataTransfer:transfer,bubbles:true})); document.querySelector('.mysql-editor-code').dispatchEvent(new DragEvent('drop',{dataTransfer:transfer,bubbles:true,cancelable:true})); })()");
  await waitFor(win,"document.querySelector('[data-testid=mysql-sql-editor]').value.includes('FROM `orders`') && document.querySelector('[data-testid=mysql-sql-editor]').value.includes('LIMIT 20')",'拖表生成查询');
  await click(win,testId('mysql-sql-tab'));
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-sql-editor]').value"),original,'拖表不会覆盖已有 SQL');
  await fill(win,testId('mysql-sql-editor'),'SELECT sort_probe FROM orders');
  await click(win,testId('mysql-query-run'));
  await click(win,'[data-testid=mysql-query-sort][data-column=id]');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-query-row] td:nth-child(2)').textContent.trim()"),'1','结果升序使用数字比较');
  await click(win,'[data-testid=mysql-query-sort][data-column=id]');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-query-row] td:nth-child(2)').textContent.trim()"),'10','结果支持降序');
  state.browseFixture = true;
  await click(win,'[data-testid=mysql-table-item][data-table-name=orders]');
  await textContains(win,'mysql-table-structure','bigint');
  await click(win,testId('mysql-table-preview-tab'));
  await click(win,testId('mysql-preview-run'));
  await textContains(win,'mysql-preview-summary','返回 20 行');
  assert.equal(databaseCalls.at(-1).payload.offset,0);
  assert.equal(databaseCalls.at(-1).payload.limit,20);
  const hold = {channel:'v2:mysql-preview-table',pluginInstanceId:PRIMARY_ID,result:browseFixture({offset:20})};
  state.holdNext = hold;
  const beforeScroll = databaseCalls.length;
  await evaluate("(() => { const scroll=document.querySelector('[data-testid=mysql-preview-table-scroll]'); scroll.scrollTop=scroll.scrollHeight; for(let i=0;i<3;i++) scroll.dispatchEvent(new WheelEvent('wheel',{deltaY:300,bubbles:true})); })()");
  await waitFor(win,"document.querySelector('[data-testid=mysql-preview-load-more]')?.textContent.includes('加载中')",'滚动请求正在读取');
  assert.equal(databaseCalls.length,beforeScroll+1,'连续滚动不能重复请求同一页');
  assert.equal(databaseCalls.at(-1).payload.offset,20);
  hold.release();
  await textContains(win,'mysql-preview-summary','返回 40 行');
  await evaluate("(() => { const scroll=document.querySelector('[data-testid=mysql-preview-table-scroll]'); scroll.scrollTop=scroll.scrollHeight; scroll.dispatchEvent(new WheelEvent('wheel',{deltaY:300,bubbles:true})); })()");
  await textContains(win,'mysql-preview-summary','返回 60 行');
  assert.equal(databaseCalls.at(-1).payload.offset,40);
  assert.ok(await evaluate("document.querySelector('[data-testid=mysql-preview-table-scroll]').scrollTop > 0"),'追加数据保留滚动位置');
  await fill(win,testId('mysql-table-where'),'id >= 51');
  await click(win,testId('mysql-preview-run'));
  await textContains(win,'mysql-preview-summary','返回 15 行');
  assert.equal(databaseCalls.at(-1).payload.where,'id >= 51');
  assert.equal(databaseCalls.at(-1).payload.offset,0,'新筛选从第一页读取');
  await click(win,'[data-testid=mysql-preview-sort][data-column=id]');
  await click(win,'[data-testid=mysql-preview-sort][data-column=id]');
  await textContains(win,'mysql-preview-summary','返回 15 行');
  assert.equal(databaseCalls.at(-1).payload.orderBy[0].direction,'desc','列排序必须发送到数据库');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-preview-row] td:nth-child(2)').textContent.trim()"),'65');
  await screenshot(win,'table-browser');
  await fill(win,testId('mysql-table-where'),'');
  await click(win,testId('mysql-preview-run'));
  await textContains(win,'mysql-preview-summary','返回 20 行');
  state.failPreview = true;
  await click(win,testId('mysql-preview-load-more'));
  await textContains(win,'mysql-preview-error','模拟数据预览失败');
  await textContains(win,'mysql-preview-summary','返回 20 行');
  state.failPreview = false;
  await click(win,testId('mysql-preview-retry'));
  await textContains(win,'mysql-preview-summary','返回 40 行');
  const stale = {channel:'v2:mysql-preview-table',pluginInstanceId:PRIMARY_ID,result:browseFixture({offset:40})};
  state.holdNext = stale;
  await click(win,testId('mysql-preview-load-more'));
  await fill(win,testId('mysql-table-where'),'id >= 61');
  await click(win,testId('mysql-preview-run'));
  await textContains(win,'mysql-preview-summary','返回 5 行');
  stale.release();
  await new Promise(resolve => setTimeout(resolve,120));
  await textContains(win,'mysql-preview-summary','返回 5 行');
  assert.equal(await evaluate("document.querySelectorAll('[data-testid=mysql-preview-row]').length"),5,'旧分页响应不能混入新条件');
  state.browseFixture = false;
  await click(win,testId('mysql-sql-tab'));
}
module.exports = {browseFixture,assertSqlAssistanceAndBrowse};
