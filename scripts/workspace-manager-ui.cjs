const assert = require('node:assert/strict');
module.exports = async ({evaluate,click,until,connectionRequests,opened,redisCalls,snapshot}) => {
  const server='[data-testid=server-workspace]';
  const connections=connectionRequests.length, terminals=opened.length, reads=redisCalls.length;
  await click(server+' [data-testid=workspace-switcher]');
  await until("document.querySelector('[data-testid=workspace-manager]')?.textContent.includes('并存验证缓存')",'工作区列表显示后台 Redis');
  await snapshot('workspace-manager.png');
  await click('[data-workspace-resume=redis-workspace-coexistence]');
  await until("document.querySelector('[data-testid=redis-workspace-back]')?.getClientRects().length > 0",'从列表继续 Redis 工作区');
  assert.equal(redisCalls.length,reads,'工作区切换不重复读取 Redis');
  await click('[data-testid=redis-workspace] [data-testid=workspace-switcher]');
  await click('[data-workspace-resume=server-workspace-smoke]');
  await until("document.querySelector('[data-testid=server-workspace-back]')?.getClientRects().length > 0",'从列表回到原服务器终端');
  assert.equal(connectionRequests.length,connections,'工作区切换不发起连接');
  assert.equal(opened.length,terminals,'工作区切换不创建终端');
  await click(server+' [data-testid=workspace-switcher]');
  await click('[data-workspace-resume=mysql-workspace-coexistence]');
  await until("document.querySelector('[data-testid=mysql-workspace-back]')?.getClientRects().length > 0",'从列表继续 MySQL 工作区');
  const sql=await evaluate("document.querySelector('[data-testid=mysql-sql-editor]').value");
  await click('[data-testid=mysql-database-workspace] [data-testid=workspace-switcher]');
  await click('[data-workspace-resume=server-workspace-smoke]');
  await until("document.querySelector('[data-testid=server-workspace-back]')?.getClientRects().length > 0",'从 MySQL 返回原服务器');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-sql-editor]').value"),sql,'切换保留后台 MySQL 草稿');
  await click(server+' [data-testid=workspace-switcher]');
  await click('[data-workspace-close=redis-workspace-coexistence]');
  await until("document.querySelector('[data-testid=redis-workspace-confirm-close]')",'关闭后台工作区沿用确认流程');
  await click('[data-testid=redis-workspace-confirm-close]');
  await until("!document.querySelector('[data-testid=redis-workspace]')",'仅关闭目标 Redis 工作区');
  assert.equal(await evaluate("document.querySelector('[data-testid=server-workspace]').hidden"),false,'关闭后台工作区不隐藏当前工作区');
  await click(server+' [data-testid=workspace-connection-settings]');
  await until("document.querySelector('[data-testid=plugin-editor-workspace]')?.textContent.includes('工作区验证服务器')",'连接配置直达当前插件编辑器');
  assert.equal(connectionRequests.length,connections,'打开配置不自动断开或连接');
  await until("document.querySelector('[data-testid=plugin-editor-confirmation]')",'连接中的配置编辑保留影响确认');
  await evaluate("[...document.querySelectorAll('[data-testid=plugin-editor-confirmation] button')].find(button => button.textContent.trim() === '取消').click()");
  await until("!document.querySelector('[data-testid=plugin-editor-workspace]')",'未修改配置可直接返回');
  await click('[data-testid=plugin-open-workspace]');
  await until("document.querySelector('[data-testid=server-workspace-back]')?.getClientRects().length > 0",'配置返回后继续原工作区');
  assert.equal(opened.length,terminals,'配置浏览保留原终端');
};
