const assert = require('node:assert/strict');
module.exports = async ({evaluate,click,until,connectionRequests,opened,redisCalls,snapshot,win,scope}) => {
  const server='[data-testid=server-workspace]';
  const connections=connectionRequests.length, terminals=opened.length, reads=redisCalls.length;
  win.webContents.send('v2:confirmations-changed',[{requestId:'workspace-global-navigation',...scope,expiresAt:Date.now()+60000,capability:'fs.write',summary:'合成导航验证'}]);
  await until(`document.querySelector('${server} [data-testid=workspace-confirmation-notice]')?.getAttribute('aria-label') === '1 项操作待确认，打开消息中心'`,'工作区页头收到全局提醒');
  const originalSize=win.getContentSize();
  for (const width of [1440,1280,1000,800]) {
    win.setContentSize(width,920);
    await until(`innerWidth === ${width}`,'全局入口窄窗验收');
    await win.webContents.capturePage(undefined,{stayHidden:true,stayAwake:true});
    const geometry=await evaluate(`(() => {
      const header=document.querySelector('${server} header'), button=header.querySelector('[data-testid=workspace-confirmation-notice]');
      const rect=button.getBoundingClientRect();
      const badge = selector => {
        const element=header.querySelector(selector), bounds=element?.getBoundingClientRect();
        return {count:element?.textContent,visible:Boolean(bounds?.width && bounds.height && bounds.left>=0 && bounds.right<=innerWidth && bounds.top>=0 && bounds.bottom<=innerHeight)};
      };
      return {overflow:header.scrollWidth>header.clientWidth,visible:rect.width>=28&&rect.left>=0&&rect.right<=innerWidth,label:button.getAttribute('aria-label'),workspace:badge('[data-testid=workspace-switcher] [data-utility-count]'),messages:badge('[data-testid=updates-count]')};
    })()`);
    assert.deepEqual(geometry,{overflow:false,visible:true,label:'1 项操作待确认，打开消息中心',workspace:{count:'3',visible:true},messages:{count:'1',visible:true}},'宽窄窗口均保留工作区和消息数量且不撑破页头：'+width);
  }
  win.setContentSize(...originalSize);
  await until(`innerWidth === ${originalSize[0]}`,'恢复工作区宽度');
  await click(server+' [data-testid=workspace-confirmation-notice]');
  await until("document.querySelector('[data-testid=confirmation-message-review]')",'工作区打开环境列表');
  await click('[data-testid=confirmation-message-review]');
  await until("document.querySelector('[data-testid=confirmation-review] [data-feature=confirmations]')",'工作区中直接展开确认详情');
  assert.equal(await evaluate("document.querySelector('[data-testid=server-workspace]').hidden"),false,'小弹窗确认不隐藏当前工作区');
  await click('[data-testid=confirmation-review-page]');
  await until("document.querySelector('[data-feature=confirmations]') && document.querySelector('#detail-main')?.dataset.selectionKind === 'environment' && document.querySelector('[data-testid=server-workspace]')?.hidden",'跳转到环境确认页且保留原工作区');
  await click('[data-testid=project-rail] [data-testid=workspace-switcher]');
  await click('[data-workspace-resume=server-workspace-smoke]');
  await until("document.querySelector('[data-testid=server-workspace-back]')?.getClientRects().length > 0",'可返回原工作区');
  assert.equal(opened.length,terminals,'查看确认不重建终端');
  assert.equal(connectionRequests.length,connections,'查看确认不自动连接或断开');
  win.webContents.send('v2:confirmations-changed',[]);
  await click(server+' [data-testid=workspace-switcher]');
  await until("document.querySelector('[data-testid=workspace-manager]')?.textContent.includes('并存验证缓存')",'工作区列表显示后台 Redis');
  await snapshot('workspace-manager.png');
  await click('[data-workspace-resume=redis-workspace-coexistence]');
  await until("document.querySelector('[data-testid=redis-workspace-back]')?.getClientRects().length > 0",'从列表继续 Redis 工作区');
  assert.equal(redisCalls.length,reads,'工作区切换不重复读取 Redis');
  await click('[data-testid=redis-workspace] [data-testid=workspace-switcher]');
  await click('[data-workspace-resume=server-workspace-smoke]');
  await until("document.querySelector('[data-testid=server-workspace-back]')?.getClientRects().length > 0",'从列表回到原服务器终端');
  assert.equal(connectionRequests.length,connections,'工作区切换不发起连接');
  assert.equal(opened.length,terminals,'工作区切换不创建终端');
  await click(server+' [data-testid=workspace-switcher]');
  await click('[data-workspace-resume=mysql-workspace-coexistence]');
  await until("document.querySelector('[data-testid=mysql-workspace-back]')?.getClientRects().length > 0",'从列表继续 MySQL 工作区');
  const sql=await evaluate("document.querySelector('[data-testid=mysql-sql-editor]').value");
  await click('[data-testid=mysql-database-workspace] [data-testid=workspace-switcher]');
  await click('[data-workspace-resume=server-workspace-smoke]');
  await until("document.querySelector('[data-testid=server-workspace-back]')?.getClientRects().length > 0",'从 MySQL 返回原服务器');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-sql-editor]').value"),sql,'切换保留后台 MySQL 草稿');
  await click(server+' [data-testid=workspace-switcher]');
  await click('[data-workspace-close=redis-workspace-coexistence]');
  await until("document.querySelector('[data-testid=redis-workspace-confirm-close]')",'关闭后台工作区沿用确认流程');
  await click('[data-testid=redis-workspace-confirm-close]');
  await until("!document.querySelector('[data-testid=redis-workspace]')",'仅关闭目标 Redis 工作区');
  assert.equal(await evaluate("document.querySelector('[data-testid=server-workspace]').hidden"),false,'关闭后台工作区不隐藏当前工作区');
  await click(server+' [data-testid=server-workspace-back]');
  await click('[data-testid=plugin-action-edit]');
  await until("document.querySelector('[data-testid=plugin-editor-workspace]')?.textContent.includes('工作区验证服务器')",'从插件详情修改当前插件连接配置');
  assert.equal(connectionRequests.length,connections,'打开配置不自动断开或连接');
  await until("document.querySelector('[data-testid=plugin-editor-confirmation]')",'连接中的配置编辑保留影响确认');
  await evaluate("[...document.querySelectorAll('[data-testid=plugin-editor-confirmation] button')].find(button => button.textContent.trim() === '取消').click()");
  await until("!document.querySelector('[data-testid=plugin-editor-workspace]')",'未修改配置可直接返回');
  await click('[data-testid=plugin-open-workspace]');
  await until("document.querySelector('[data-testid=server-workspace-back]')?.getClientRects().length > 0",'配置返回后继续原工作区');
  assert.equal(opened.length,terminals,'配置浏览保留原终端');
};
