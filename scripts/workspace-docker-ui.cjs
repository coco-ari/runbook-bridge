const assert = require('node:assert/strict');
module.exports = async ({evaluate,click,clickText,until,wait,win,setViewport,snapshot,dockerState,opened,closed,errors}) => {
  const visible = selector => "Boolean(document.querySelector(" + JSON.stringify(selector) + ")?.getClientRects().length)";
  const nativeClick = async selector => {
    win.webContents.focus();
    await win.webContents.capturePage(undefined,{stayHidden:true,stayAwake:true});
    // 菜单初次出现时可能仍在视口外，等待定位完成且命中目标后再发送原生点击。
    await until("(() => {const target=document.querySelector(" + JSON.stringify(selector) + ");const r=target?.getBoundingClientRect();if(!r||r.width<=0||r.height<=0||r.left<0||r.top<0||r.right>innerWidth+1||r.bottom>innerHeight+1)return false;const hit=document.elementFromPoint(r.left+r.width/2,r.top+r.height/2);return Boolean(hit&&target.contains(hit));})()",'原生点击目标完成定位');
    const point = await evaluate("(() => {const r=document.querySelector(" + JSON.stringify(selector) + ").getBoundingClientRect();return {x:Math.round(r.left+r.width/2),y:Math.round(r.top+r.height/2)};})()");
    win.webContents.sendInputEvent({type:'mouseMove',...point});
    win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});
    win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point});
    await wait(100);
  };
  const count = kind => dockerState.reads.filter(item => item.kind === kind).length;
  const initialSessions = opened.length;
  assert.equal(await evaluate("document.querySelector('.server-resource-rail').getBoundingClientRect().width"),36);
  await click('[aria-label="Docker 容器"]');
  await until(visible('[aria-label="打开容器 fixture-api"]'),'Docker 列表');
  assert.ok(await evaluate(visible('.server-content-terminal')),'切换资源不改变右侧终端');
  assert.equal(opened.length,initialSessions);
  await click('[aria-label="打开容器 fixture-api"]');
  await until("document.querySelector('.server-docker-overview')?.textContent.includes('fixture-api')",'容器概览');
  await require('./workspace-layout-ui.cjs')({evaluate,until,win,root:'[data-testid=server-workspace]'});
  assert.ok(!(await evaluate(visible('.server-content-terminal'))));
  await click('[aria-label="服务器文件"]');
  assert.ok(await evaluate(visible('.server-docker-tab-panel:not([hidden])')),'资源切回文件不关闭容器内容');
  assert.equal(await evaluate("[...document.querySelectorAll('.server-file-actions button')].filter(item => item.getClientRects().length).length"),6);
  await click('[aria-label="Docker 容器"]');
  await click('[aria-label="打开容器 fixture-api"]');
  assert.equal(await evaluate('document.querySelectorAll(\'[role="tab"][title="容器 fixture-api"]\').length'),1,'同一容器标签去重');
  await clickText('日志');
  await until("document.querySelector('.server-docker-logs')?.textContent.includes('fixture request complete')",'日志正文');
  assert.ok(await evaluate("document.querySelector('.server-docker-detail').textContent.includes('日志已截断')"),'明确显示截断');
  const beforeRefresh = count('logs');
  await click('[aria-label="刷新容器内容"]');
  await until("document.querySelector('[aria-label=\"刷新容器内容\"]').disabled === false",'手动刷新结束');
  assert.equal(count('logs'),beforeRefresh + 1);
  await evaluate("(() => {const input=document.querySelector('[aria-label=\"搜索已加载日志\"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'WARN'); input.dispatchEvent(new Event('input',{bubbles:true}));})()");
  await until("document.querySelector('.server-docker-logs')?.textContent.includes('WARN') && !document.querySelector('.server-docker-logs')?.textContent.includes('complete')",'搜索只影响已加载正文');
  assert.equal(count('logs'),beforeRefresh + 1,'本地搜索不重新读取服务器');
  await evaluate("(() => {const input=document.querySelector('[aria-label=\\\"搜索已加载日志\\\"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,''); input.dispatchEvent(new Event('input',{bubbles:true}));})()");
  for (const theme of ['light','dark']) {
    await nativeClick('[data-testid="server-workspace"] [data-testid="settings-open"]');
    await nativeClick('[data-testid="theme-menu-trigger"]');
    await nativeClick('[data-testid="theme-option-' + theme + '"]');
    await until("document.documentElement.dataset.theme === '" + theme + "'",'切换主题');
    await nativeClick('[data-testid="settings-back"]');
    await until("!document.querySelector('[data-testid=settings-page]')",'返回服务器工作区');
    await snapshot('docker-workspace-' + theme + '.png');
    if (theme === 'light') { await click('[aria-label="服务器文件"]'); await snapshot('docker-workspace-files-light.png'); await click('[aria-label="Docker 容器"]'); }
  }
  await clickText('资源');
  await until("document.querySelector('.server-docker-detail').textContent.includes('5.2%')",'资源采样');
  await click('[role="tab"][title="终端 1"]');
  const pausedAt = count('stats');
  await wait(5200);
  assert.equal(count('stats'),pausedAt,'隐藏容器标签后停止采样');
  assert.equal(opened.length,initialSessions,'容器与终端切换不重新建立会话');
  assert.equal(closed.length,0,'容器操作不关闭宿主机终端');
  await click('[aria-label="服务器文件"]');
  await setViewport(960,640);
  await evaluate("(() => {const handle=document.querySelector('[aria-label=\"调整文件树宽度\"]'); handle.focus(); for(let i=0;i<10;i++)handle.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true,cancelable:true}));})()");
  await wait(150);
  const narrow = await evaluate("(() => {const rail=document.querySelector('.server-resource-rail').getBoundingClientRect(); const toolbar=document.querySelector('.server-file-toolbar').getBoundingClientRect();return {rail:rail.width,width:document.querySelector('.server-resource-panel').getBoundingClientRect().width,inside:[...document.querySelectorAll('.server-file-actions button')].every(button=>{const box=button.getBoundingClientRect();return box.left>=toolbar.left&&box.right<=toolbar.right;})};})()");
  if (narrow.width === 0) await click('[aria-label="服务器文件"]');
  else assert.ok(narrow.inside,'窄侧栏按钮完整可见');
  assert.equal(narrow.rail,36,'窄窗口资源栏仍可见');
  assert.equal(await evaluate("[...document.querySelectorAll('.server-file-actions button')].filter(item=>item.getClientRects().length).length"),6);
  await click('[aria-label="最大化工作区"]');
  assert.ok(await evaluate(visible('.server-resource-rail')),'侧栏折叠后资源栏保留');
  await click('[aria-label="Docker 容器"]');
  await until(visible('.server-docker-tree'),'点击图标恢复侧栏');
  await setViewport(1440,920);
  for (let index=2;index<=6;index++) await click('[aria-label="打开容器 fixture-' + index + '"]');
  await click('[aria-label="打开容器 fixture-7"]');
  assert.ok(await evaluate("document.querySelector('.server-workspace').textContent.includes('最多保留 6 个容器标签')"));
  assert.equal(await evaluate('document.querySelectorAll(\'[role="tab"][title^="容器 "]\').length'),6);
  await click('[aria-label="关闭容器 fixture-6"]');
  await click('[aria-label="打开容器 fixture-7"]');
  await click('[role="tab"][title="容器 fixture-api"]');
  dockerState.missing = true;
  await clickText('概览');
  await until("document.querySelector('.server-docker-detail').textContent.includes('容器已删除')",'容器已删除');
  assert.equal(opened.length,initialSessions);
  dockerState.missing = false;
  dockerState.delay = 400;
  await click('[aria-label="刷新容器内容"]');
  await wait(30);
  await click('[aria-label="关闭容器 fixture-api"]');
  await wait(450);
  assert.ok(dockerState.cancels.length > 0,'关闭标签取消仍在执行的读取');
  assert.equal(await evaluate('document.querySelectorAll(\'[role="tab"][title="容器 fixture-api"]\').length'),0,'迟到结果不重开标签');
  await setViewport(960,640);
  await require('./workspace-layout-ui.cjs')({evaluate,until,win,root:'[data-testid=server-workspace]'});
  await click('[aria-label="关闭终端 1"]');
  await until("document.querySelectorAll('.server-terminal-tab-panel').length === 0",'关闭全部终端');
  await require('./workspace-layout-ui.cjs')({evaluate,until,win,root:'[data-testid=server-workspace]'});
  const remainingContainers = await evaluate("[...document.querySelectorAll('.server-tabs [aria-label^=\"关闭容器 \"]')].map(button=>button.getAttribute('aria-label'))");
  for (const label of remainingContainers) await click('[aria-label=' + JSON.stringify(label) + ']');
  await until("document.querySelector('.server-tabs-empty')?.getClientRects().length > 0",'空终端工作区');
  await require('./workspace-layout-ui.cjs')({evaluate,until,win,root:'[data-testid=server-workspace]'});
  assert.deepEqual(errors,[]);
};
