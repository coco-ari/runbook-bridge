const assert = require('node:assert/strict');

module.exports = async function({evaluate,click,doubleClick,clickText,until,wait,win,setViewport,snapshot,nativeTheme,opened,closed,writes,terminalSessions,errors,log,downloadReveals,downloadRetries,setJobs}) {
  const has = selector => `document.querySelector(${JSON.stringify(selector)})`;
  const pane = '.server-terminal-tab-panel:not([hidden])';
  const visiblePanes = `${has('.server-terminal-panes')}.querySelectorAll(${JSON.stringify(pane)})`;
  const fill = async (selector,value) => { await evaluate(`(() => {const el=${has(selector)};el.focus();Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));})()`); await wait(80); };
  const layout = async text => {await evaluate(`${has('[aria-label="分屏布局"]')}.focus()`); win.webContents.sendInputEvent({type:'keyDown',keyCode:'Space'}); win.webContents.sendInputEvent({type:'keyUp',keyCode:'Space'}); await until("document.querySelector('[role=menuitemradio]')",'布局菜单'); await evaluate(`[...document.querySelectorAll('[role=menuitemradio],[role=menuitem]')].find(el=>el.textContent.includes(${JSON.stringify(text)})).click()`); await wait(150);};
  await until("document.querySelector('.server-terminal-tab-panel .xterm-rows')?.textContent.includes('operator@demo')", '初始终端');
  await wait(150);
  const first = opened[0];
  await layout('左右分屏');
  await until(`${visiblePanes}.length === 2 && [...${visiblePanes}].every(el=>el.querySelector('.xterm-helper-textarea'))`, '双终端');
  assert.equal(opened.length,2);
  const sessions = [...terminalSessions.keys()];
  const input = async index => {
    await evaluate(`${visiblePanes}[${index}].querySelector('.xterm-helper-textarea').focus()`);
    win.webContents.focus();
    win.webContents.sendInputEvent({type:'keyDown',keyCode:index?'B':'A'});
    win.webContents.sendInputEvent({type:'char',keyCode:index?'b':'a'});
    win.webContents.sendInputEvent({type:'keyUp',keyCode:index?'B':'A'});
    await wait(160);
  };
  const before = writes.length; await input(0); await input(1);
  assert.deepEqual(writes.slice(before).map(item=>[item.sessionId,item.data]),[[first,'a'],[sessions[1],'b']], '分屏仅向焦点会话发送输入');
  const paneOrder=()=>evaluate(`[...${visiblePanes}].sort((a,b)=>a.getBoundingClientRect().x-b.getBoundingClientRect().x).map(el=>el.dataset.terminalId)`);
  const initialOrder=await paneOrder();
  await layout('交换左右');assert.deepEqual(await paneOrder(),initialOrder.toReversed(),'终端交换左右');
  const afterSwap=writes.length;await input(0);await input(1);
  assert.deepEqual(writes.slice(afterSwap).map(item=>[item.sessionId,item.data]),[[first,'a'],[sessions[1],'b']],'交换后输入仍发送到对应会话');
  assert.equal(opened.length,2);assert.equal(closed.length,0,'交换不关闭会话');
  await layout('交换左右');
  await evaluate(`${has('[aria-label=工作区标签] [role=tab][aria-selected=true]')}.dispatchEvent(new KeyboardEvent('keydown',{key:'F2',bubbles:true}))`);
  await until(has('[aria-label="终端名称"]'),'重命名');
  await fill('[aria-label="终端名称"]','查看日志'); await clickText('保存');
  await until("[...document.querySelectorAll('[role=tab]')].some(el=>el.textContent==='查看日志')",'新名称');
  await evaluate(`[...document.querySelectorAll('[role=tab]')].find(el=>el.textContent==='查看日志').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',altKey:true,bubbles:true}))`);
  assert.ok(await evaluate("document.querySelector('[aria-label=工作区标签] [role=tab]').textContent.includes('查看日志')"),'键盘调整标签顺序');
  await layout('上下分屏');
  await until("document.querySelector('.server-terminal-panes').dataset.layout==='vertical'",'纵向分屏');
  const boxes = await evaluate(`[...${visiblePanes}].map(el=>{const r=el.getBoundingClientRect();return {x:r.x,y:r.y,w:r.width,h:r.height}})`);
  assert.equal(boxes[0].x,boxes[1].x); assert.ok(Math.abs(boxes[0].y-boxes[1].y)>100);
  await click('[aria-label="调整工作区分屏"]');
  await evaluate(`${has('[aria-label="调整工作区分屏"]')}.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowUp',bubbles:true}))`);
  assert.equal(await evaluate(`${has('[aria-label="调整工作区分屏"]')}.getAttribute('aria-valuenow')`),'45');
  await layout('单栏'); await layout('左右分屏');
  assert.equal(opened.length,2,'布局变更不重新登录'); assert.equal(closed.length,0);

  await click('[aria-label="切换到详情列表"]');
  await until(has('[aria-label="筛选当前目录已加载项"]'),'详情筛选');
  await fill('[aria-label="筛选当前目录已加载项"]','srv');
  await until("document.querySelectorAll('.server-tree-row').length===1",'当前批次筛选');
  await click('[role=treeitem][title="/srv"]');
  await until(has('[role=treeitem][title="/srv/example.log"]'),'详情进入目录');
  assert.equal(await evaluate(`${has('[aria-label="筛选当前目录已加载项"]')}.value`),'','进入目录清除筛选');
  assert.ok(await evaluate("document.querySelector('.server-file-size').textContent.length>0"));
  await click('[aria-label="按名称排序"]');
  assert.equal(await evaluate("[...document.querySelectorAll('.server-tree-name')].map(el=>el.textContent).filter(name=>name.startsWith('example'))[0]"),'example.log','名称倒序');
  await click('[aria-label="按大小排序"]');
  await click('[aria-label="定位终端当前目录"]');
  await wait(250);
  assert.ok(await evaluate("document.querySelector('.server-file-tree').dataset.view==='details'"),'定位保留详情视图');

  await layout('单栏');
  log.content='HEAD_MARK\n'+'示例日志 error\n'.repeat(240)+'TAIL_MARK\n'; log.mtime++;
  await doubleClick('[role=treeitem][title="/srv/example.log"]');
  await until("document.querySelector('.server-preview-content')?.textContent.includes('HEAD_MARK')",'日志头部');
  assert.equal(await evaluate("document.querySelectorAll('.server-tabs-toolbar').length"),1,'文件与终端共用一排标签');
  assert.equal(await evaluate("document.querySelectorAll('.server-document-panel:not([hidden])').length"),1,'默认只显示当前标签');
  assert.equal(await evaluate("document.querySelector('.server-document-panel:not([hidden])').dataset.documentKind"),'file');
  assert.ok(await evaluate("document.querySelector('button[aria-label=分屏布局]').getBoundingClientRect().width<=28"),'布局入口紧凑');
  await click('[role=tab][title="查看日志"]');
  assert.equal(await evaluate("document.querySelector('.server-file-preview').getBoundingClientRect().height"),0,'切换到终端收起文件内容');
  await doubleClick('[role=treeitem][title="/srv/example.log"]');
  await until("document.querySelector('.server-file-preview').getBoundingClientRect().height>200",'重复打开已有文件可重新激活');
  await click('[data-testid="server-layout-toggle"]');
  assert.equal(await evaluate("document.querySelector('.server-document-panel:not([hidden])').dataset.documentKind"),'file','最大化保留当前文件');
  await click('[data-testid="server-layout-toggle"]');
  await require('./workspace-layout-ui.cjs')({evaluate,until,win,root:'[data-testid=server-workspace]'});
  nativeTheme.themeSource='light';await setViewport(1280,800);
  await snapshot('ssh-unified-file-light.png');
  await layout('左右分屏');
  assert.equal(await evaluate("document.querySelectorAll('.server-document-panel:not([hidden])').length"),2);
  assert.equal(await evaluate(`${visiblePanes}.length`),1,'文件与一个终端配对分屏');
  await click('[aria-label="Docker 容器"]');
  await click('[aria-label="打开容器 fixture-api"]');
  await until("document.querySelector('.server-docker-overview')?.textContent.includes('fixture-api')",'容器替换当前窗格');
  assert.equal(await evaluate(`${visiblePanes}.length`),1,'容器切换保留另一侧终端');
  await click('[role=tab][title="/srv/example.log"]');
  await click('[aria-label="关闭容器 fixture-api"]');
  await click('[aria-label="服务器文件"]');
  assert.equal(opened.length,2,'文件和容器切换不重建会话');assert.equal(closed.length,0);
  await snapshot('ssh-unified-split-light.png');
  await clickText('跟随');
  await until("document.querySelector('.server-preview-footer')?.textContent.includes('跟随中')",'跟随开启');
  log.content+='APPENDED 中文😀\n';log.mtime++;
  await until("document.querySelector('.server-preview-content')?.textContent.includes('APPENDED 中文😀')",'增量中文');
  assert.equal(await evaluate("document.querySelector('.server-preview-content').textContent.split('HEAD_MARK').length"),2,'不会重复拼接旧内容');
  await fill('[aria-label="搜索已加载文件内容"]','error');
  await until("document.querySelectorAll('.server-preview-content mark').length===240",'搜索高亮');
  assert.ok(await evaluate("!document.querySelector('.server-preview-footer').textContent.includes('跟随中')"),'搜索暂停跟随');
  const paused=log.reads.length;await wait(3300);assert.equal(log.reads.length,paused);
  await fill('[aria-label="搜索已加载文件内容"]','');
  await clickText('跟随'); await wait(150);
  await layout('单栏');
  await click('[role=tab][title="查看日志"]');
  const hiddenFileReads=log.reads.length;await wait(3300);
  assert.equal(log.reads.length,hiddenFileReads,'隐藏的文件标签停止跟随读取');
  await click('[role=tab][title="/srv/example.log"]');
  await layout('左右分屏');
  await click('[data-testid="server-workspace-back"]');
  const hidden=log.reads.length;log.content+='AFTER_HIDDEN\n';log.mtime++;
  await wait(3300); assert.equal(log.reads.length,hidden,'隐藏期间无日志读取');
  await click('[data-testid="plugin-open-workspace"]');
  await until("document.querySelector('.server-preview-content').textContent.includes('AFTER_HIDDEN')",'可见后继续');
  log.content='ROTATED 文件\n';log.mtime++;
  await until("document.querySelector('.server-preview-content').textContent==='ROTATED 文件\\n'",'截断重新读取');
  assert.ok(await evaluate("document.querySelector('.server-preview-footer').textContent.includes('截断')"));
  log.content+='line\n'.repeat(6000);log.mtime++;
  await until("document.querySelector('.server-preview-footer').textContent.includes('5000')",'有界行缓存');
  assert.ok(await evaluate("document.querySelector('.server-preview-content').textContent.split('\\n').length<=5000"));
  await evaluate("const el=document.querySelector('.server-preview-content');el.scrollTop=0;el.dispatchEvent(new Event('scroll',{bubbles:true}))");
  await until("!document.querySelector('.server-preview-footer').textContent.includes('跟随中')",'上翻暂停');

  for (const theme of ['light','dark']) {
    nativeTheme.themeSource=theme;
    await setViewport(960,700);
    assert.ok(await evaluate("document.documentElement.scrollWidth<=innerWidth"),'窄窗口不溢出');
    assert.ok(await evaluate(`[...${visiblePanes}].every(el=>el.querySelector('.server-terminal-container').getBoundingClientRect().height>60)`),'分屏终端可用');
    for (let step=0;step<5;step++) { await evaluate("document.querySelector('[aria-label=调整工作区分屏]').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',bubbles:true}))"); await wait(40); }
    assert.equal(await evaluate("document.querySelector('[aria-label=调整工作区分屏]').getAttribute('aria-valuenow')"),'25');
    assert.ok(await evaluate("[...document.querySelectorAll('.server-document-panel:not([hidden])')].every(panel=>{const p=panel.getBoundingClientRect();return [...panel.querySelectorAll('.server-workspace-toolbar button')].filter(button=>button.getClientRects().length).every(button=>{const b=button.getBoundingClientRect();return b.left>=p.left-1&&b.right<=p.right+1})})"),'拖到最窄比例时操作按钮仍在窗格内');
    await evaluate("document.querySelector('[aria-label=调整工作区分屏]').dispatchEvent(new KeyboardEvent('keydown',{key:'Home',bubbles:true}))");
    await snapshot('ssh-productivity-'+theme+'.png');
  }
  await setViewport(1440,920);
  await layout('单栏');
  await click('[aria-label="Docker 容器"]');
  await click('[aria-label="打开容器 fixture-api"]');
  await click('[role=tab][title="/srv/example.log"]');
  await click('[aria-label="关闭文件预览"]');
  await until("document.querySelector('[aria-label=\"打开容器 fixture-api\"]').getAttribute('aria-pressed')==='true'",'关闭文件后相邻容器同步选中状态');
  await click('[aria-label="关闭容器 fixture-api"]');
  await click('[aria-label="服务器文件"]');
  await require('./workspace-download-recovery-ui.cjs')({evaluate,click,until,snapshot,downloadReveals,downloadRetries,setJobs});
  await layout('单栏');
  assert.equal(opened.length,2); assert.equal(closed.length,0);
  await layout('左右分屏');
  await click('[aria-label="关闭终端 1"]');
  await until(`${visiblePanes}.length===1 && document.querySelector('.server-terminal-panes').dataset.layout==='single'`,'关闭一侧恢复单栏');
  assert.deepEqual(closed,[first],'只关闭指定会话');
  assert.deepEqual(errors,[],'无界面错误');
};
