const assert = require('node:assert/strict');

module.exports = async function assertEnvironmentWorkspaceUi({win,click,fill,waitFor,textContains,testId,screenshot,databaseCalls,PRIMARY_ID,OTHER_ID,OFFLINE_ID,ENVIRONMENT_ID,returnToDetails,setExactViewport,state,plugins,runtime,assessment}) {
  const evaluate = source => win.webContents.executeJavaScript(source,true);
  const entry = id => testId('environment-plugin-workspace-'+id);
  await returnToDetails(win);
  await click(win,testId('environment-trigger-'+ENVIRONMENT_ID));
  await waitFor(win,"document.querySelector('#detail-main')?.dataset.selectionKind === 'environment'",'选择环境详情');
  await waitFor(win,`document.querySelector('${entry(PRIMARY_ID)}')?.disabled === false`,'环境详情直接工作区入口就绪');
  const before = databaseCalls.length;
  assert.equal(await evaluate(`document.querySelector('${entry(OFFLINE_ID)}') === null`),true,'未保留的离线插件不显示不可用的工作区入口');
  assert.equal(databaseCalls.length,before,'浏览环境详情不会访问数据库');
  const size=win.getContentSize();
  await setExactViewport(win,1680,980);
  await screenshot(win,'environment-workspace-entry-wide');
  await setExactViewport(win,960,640);
  const geometry = await evaluate(`(() => {
    const panel=document.querySelector('[data-testid=environment-plugin-list]'),bounds=panel.getBoundingClientRect();
    return [...panel.querySelectorAll('button')].filter(e=>e.getClientRects().length).every(e=>{const r=e.getBoundingClientRect();return r.left>=bounds.left && r.right<=bounds.right});
  })()`);
  assert.equal(geometry,true,'窄环境详情的连接和工作区按钮不得溢出');
  await screenshot(win,'environment-workspace-entry-narrow');
  await setExactViewport(win,...size);
  await click(win,entry(PRIMARY_ID));
  await textContains(win,'mysql-table-list','orders');
  await waitFor(win,"document.querySelector('[data-testid=mysql-full-window-workspace]')?.getClientRects().length > 0",'直接打开 MySQL 工作区');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-workspace-back]').getAttribute('aria-label')"),'返回环境详情');
  assert.equal(await evaluate("document.querySelector('#detail-main')?.dataset.selectionKind"),'environment','打开工作区不切换底层插件详情');
  const sql='SELECT 1 AS environment_entry_draft';
  await fill(win,testId('mysql-sql-editor'),sql);
  await returnToDetails(win);
  await waitFor(win,`document.activeElement === document.querySelector('${entry(PRIMARY_ID)}')`,'返回后焦点恢复到原工作区按钮');
  await textContains(win,'environment-plugin-workspace-'+PRIMARY_ID,'继续工作区');
  const beforeResume=databaseCalls.length;
  await click(win,entry(PRIMARY_ID));
  await waitFor(win,"document.querySelector('[data-testid=mysql-full-window-workspace]')?.getClientRects().length > 0",'继续原工作区');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-sql-editor]').value"),sql,'返回环境详情保留原 SQL');
  assert.equal(databaseCalls.length,beforeResume,'继续原工作区不会重新读取表列表');
  const primary = plugins.find(plugin => plugin.pluginInstanceId === PRIMARY_ID);
  primary.assessment = assessment('disconnected'); state.sequence++;
  win.webContents.send('v2:environment-status-changed',runtime());
  await waitFor(win,"document.querySelector('[data-testid=mysql-workspace-disconnected]')",'环境入口工作区已离线');
  await returnToDetails(win);
  await waitFor(win,`document.querySelector('${entry(PRIMARY_ID)}')?.disabled === false`,'环境详情允许离线继续已有工作区');
  const offlineCalls=databaseCalls.length;
  await click(win,entry(PRIMARY_ID));
  await waitFor(win,"document.querySelector('[data-testid=mysql-full-window-workspace]')?.getClientRects().length > 0",'环境详情离线恢复工作区');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-sql-editor]').value"),sql,'离线环境入口保留 SQL 草稿');
  assert.equal(await evaluate("document.querySelector('[data-testid=mysql-query-run]').disabled"),true,'离线进入仍禁止执行 SQL');
  assert.equal(databaseCalls.length,offlineCalls,'离线进入不读取数据库');
  await returnToDetails(win);
  primary.assessment = assessment('connected'); state.sequence++;
  win.webContents.send('v2:environment-status-changed',runtime());
  await click(win,entry(OTHER_ID));
  const active='[data-testid=mysql-full-window-workspace]:not([hidden])';
  await waitFor(win,`document.querySelector('${active} [data-testid=mysql-table-list]')?.textContent.includes('reports')`,'第二个数据库工作区正常打开');
  assert.equal(await evaluate("document.querySelectorAll('[data-testid=mysql-full-window-workspace]').length"),2,'两个数据库工作区可同时保留');
  assert.equal(await evaluate(`document.querySelector('${active} [data-testid=mysql-sql-editor]').value.includes('environment_entry_draft')`),false,'新工作区不串用旧 SQL');
  const otherSql='SELECT 2 AS second_workspace_draft';
  await fill(win,active+' '+testId('mysql-sql-editor'),otherSql);
  await click(win,active+' '+testId('mysql-workspace-back'));
  await click(win,entry(PRIMARY_ID));
  assert.equal(await evaluate(`document.querySelector('${active} [data-testid=mysql-sql-editor]').value`),sql,'切回第一个工作区恢复原 SQL');
  await click(win,active+' '+testId('mysql-workspace-close'));
  await click(win,testId('mysql-workspace-confirm-close'));
  await waitFor(win,"document.querySelector('[data-testid=mysql-edit-discard-confirm]')",'关闭脏工作区再次明确提示草稿丢弃');
  await click(win,testId('mysql-edit-discard-confirm'));
  await waitFor(win,"document.querySelectorAll('[data-testid=mysql-full-window-workspace]').length === 1",'只关闭指定工作区');
  await click(win,entry(OTHER_ID));
  assert.equal(await evaluate(`document.querySelector('${active} [data-testid=mysql-sql-editor]').value`),otherSql,'关闭其他工作区不影响当前 SQL');
  await click(win,active+' '+testId('mysql-workspace-back'));
  assert.equal(await evaluate("document.querySelector('#detail-main')?.dataset.selectionKind"),'environment');
  process.stdout.write('环境详情工作区入口通过：未保留离线入口隐藏、已保留离线恢复、直接进入、返回焦点、SQL 保留、跨插件隔离与窄屏布局。\n');
};
